async function userIdOf(client: PoolClient, email: string): Promise<number> {
  const r = await client.query('SELECT user_id FROM users WHERE email = $1', [email]);
  if ((r.rowCount ?? 0) === 0) throw new Error(`ไม่พบบัญชีผู้ใช้ ${email} ในระบบ (กรุณารัน db:setup ก่อน)`);
  return r.rows[0].user_id as number;
}

async function writePlaceholderPdf(file: string, title: string): Promise<void> {
  const doc = await PDFDocument.create();
  const page = doc.addPage();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  page.drawText(title, { x: 60, y: 760, size: 18, font });
  page.drawText('Presentation sample file generated by db:seed-presentation.', { x: 60, y: 730, size: 11, font });
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, await doc.save());
}

