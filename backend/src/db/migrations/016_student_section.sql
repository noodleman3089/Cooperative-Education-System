--    "ห้อง" คือเลขห้องพัก แล้วใส่เป็น `accommodations.room_no`
--    พอได้ไฟล์จริง (2026-09-04) บรรทัดบนฟอร์มคือ
--        "สาขาวิชา ........ นักศึกษาชั้นปีที่ ..... ห้อง ....."
--    → มันอยู่ในบล็อก **ตัวตนของนักศึกษา** ข้าง "ชั้นปีที่" ไม่ใช่ในบล็อกที่อยู่
--    (บล็อกที่อยู่ของฟอร์มมีแค่ เลขที่ · อาคาร · ถนน · ซอย · ตำบล · อำเภอ · จังหวัด
--     · รหัสไปรษณีย์ — ไม่มีช่องห้องเลย)
--
-- ⛔ **ไม่ลบ `accommodations.room_no`** — หอพัก/คอนโดมีเลขห้องจริงและนักศึกษากรอกไปแล้ว
--    ของสองอย่างนี้คนละความหมาย ไม่ใช่ของซ้ำ · `room_no` แค่ไม่ได้อยู่บนฟอร์ม
