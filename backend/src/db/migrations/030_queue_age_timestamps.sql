-- "แถวนี้เข้าคิวมาตั้งแต่เมื่อไหร่" — ทั้งสองตารางไม่เคยเก็บไว้เลย
--
-- เหตุผล: หน้าแรกของเจ้าหน้าที่ (spec-E ข้อ 4 · SB8) ต้องตอบสองอย่างที่หาจากที่อื่นไม่ได้
--   · การ์ดใบใหญ่ลำดับ 1 นับ "คำร้องที่ค้างเกิน 7 วัน" เป็นหนึ่งในตัวตัดสินฤดูกาล overdue
--   · กองงาน "ค้างที่คณบดี" ต้องบอกว่าค้างมากี่วัน ไม่ใช่แค่ว่ามีกี่ใบ
-- ไม่มีคอลัมน์เวลาเลยทั้งสองตาราง (`officer_approved_at` เกิดตอน *จบ* คิว ไม่ใช่ตอนเข้าคิว)
--
-- ⛔ **จงใจให้เป็น NULL ได้ และไม่ backfill** — แถวที่มีอยู่ก่อน migration นี้
--    ไม่มีใครรู้จริง ๆ ว่าเข้าคิวมาตั้งแต่เมื่อไหร่ · การใส่ NOW() ให้ทุกแถวคือการ
--    ประกาศว่า "ทุกใบที่ค้างมาสามเดือนเพิ่งเข้ามาวันนี้" ซึ่งแย่กว่าการบอกว่าไม่รู้
--    → SB8 อ่าน NULL เป็น "ไม่ทราบอายุ" และ **ไม่นับเป็นเลยกำหนด**
--       (นับเป็นเลยกำหนดจากค่าที่เดาเอาเอง = ตัวเลขบนหน้าแรกโกหก)
--    แถวใหม่ทุกแถวได้ DEFAULT NOW() ตั้งแต่วินาทีที่ migration นี้รัน
ALTER TABLE intent_forms ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW();
ALTER TABLE official_documents ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW();
