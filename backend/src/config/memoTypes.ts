export interface MemoType {
  key: string;
  /** ชื่อหัวข้อบน dropdown ของนักศึกษา */
  label: string;
  /** บรรทัด "เรื่อง" บนกระดาษ */
  subject: string;
  /** ท่อนนำของบรรทัด "มีความประสงค์" — ต่อด้วยเหตุผลที่นักศึกษาเขียนเอง */
  intent: string;
  /** คำอธิบายใต้ dropdown ให้นักศึกษารู้ว่าควรเลือกอันไหน */
  hint: string;
}

