export const SUPERVISION_VISITS = [1, 2] as const;

const flatten = (groups: SupervisionGroup[]): SupervisionItem[] =>
  groups.flatMap((g) => g.items);

export const COMPANY_ITEM_KEYS = flatten(COMPANY_SECTION).map((i) => i.key);
export const STUDENT_ITEM_KEYS = flatten(STUDENT_SECTION).map((i) => i.key);
export const ALL_ITEM_KEYS = [...COMPANY_ITEM_KEYS, ...STUDENT_ITEM_KEYS];
export const DOCUMENT_KEYS = REQUIRED_DOCUMENT_ITEMS.map((i) => i.key);

/**
 * ตรวจก้อนคะแนนที่ส่งเข้ามา
 *
 * ⛔ **ไม่บังคับให้ตอบครบ** (ต่างจาก `evaluationRubric.ts`) แต่**คีย์แปลกปลอมต้องถูก
 * ปฏิเสธ** ไม่ใช่ตัดทิ้งเงียบๆ — ต่างจาก JSONB ประวัติของ สหกิจ 03 ตรงที่ชุดคีย์ของใบนี้
 * เป็นของตายตัวจากกระดาษ คีย์ที่ไม่รู้จักแปลว่ามีคนส่งของผิดใบมา ควรรู้ทันที
 */
export function validateSupervisionScores(raw: unknown): {
  scores: Record<string, number | null>;
  error?: string;
} {
  if (raw === null || raw === undefined) return { scores: {} };
  if (typeof raw !== 'object' || Array.isArray(raw)) {
    return { scores: {}, error: 'รูปแบบคะแนนไม่ถูกต้อง' };
  }

  const allowed = new Set(ALL_ITEM_KEYS);
  const out: Record<string, number | null> = {};

  for (const [key, value] of Object.entries(raw as Record<string, unknown>)) {
    if (!allowed.has(key)) {
      return { scores: {}, error: `พบหัวข้อประเมินที่ไม่รู้จัก: ${key}` };
    }
    // `-` บนกระดาษ → null · สตริงว่างก็ถือว่าไม่ประเมิน
    if (value === null || value === '' || value === '-') {
      out[key] = null;
      continue;
    }
    const num = typeof value === 'number' ? value : Number(value);
    if (
      !Number.isInteger(num) ||
      num < SUPERVISION_MIN_SCORE ||
      num > SUPERVISION_MAX_SCORE
    ) {
      return {
        scores: {},
        error: `คะแนนของข้อ ${key} ต้องเป็น ${SUPERVISION_MIN_SCORE}-${SUPERVISION_MAX_SCORE} หรือ "-"`,
      };
    }
    out[key] = num;
  }

  return { scores: out };
}
